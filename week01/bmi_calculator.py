"""
bmi_calculator.py —— BMI 计算器（从 notebook 抽出来的可复用零件）

这是 Day 5 的收尾作业：把 Day 3 练习 C 写在 notebook 里的 BMI 逻辑，
变成一个正式、可复用的 .py 文件。

文件里有三块内容，看懂这三块就理解了「一个正式的 Python 文件长什么样」：

  1. 函数定义（def ...）—— 把逻辑包起来，起个名字，随时调用
     ★ 函数是 Day 8 的内容，今天你【不需要会写】，只要能读懂并跑通。
  2. assert 自检 —— 用代码验证代码，这是 Day 2 就欠下的那两条。
  3. if __name__ == "__main__": —— Day 1 你问过它防什么，今天它终于真正派上用场。

运行方式（在项目根目录的终端里）：
    .venv/bin/python week01/bmi_calculator.py
"""

# ─────────────────────────────────────────────────────────
# 第 1 块：函数定义
#
# def 的意思就是 define（定义）。
# 括号里的 height_m / weight_kg 叫「参数」：调用时必须给值，函数内部用这名字引用。
# return 的意思是「把这个值交出去」，函数到此结束。
#
# 为什么要包成函数？因为同样一件事你要算很多次（不同人的身高体重）。
# 写成函数，就能 bmi(1.75, 70)、bmi(1.60, 45) 这样反复调用，逻辑只用写一遍。
# ─────────────────────────────────────────────────────────

def calc_bmi(height_m, weight_kg):
    """算出 BMI。身高单位米，体重单位公斤。输入不合法时返回 None。"""
    # 挡住非法输入。这是 Day 3 练习 C 第 3 点的要求。
    if height_m <= 0 or weight_kg <= 0:
        return None
    return weight_kg / (height_m ** 2)


def bmi_category(bmi_value):
    """根据 BMI 数值给出分类。用中国成人标准。"""
    # 注意分支顺序：因为用的是「<」从小到大，天然正确（Day 3 练习 B 你也是这么写的）
    if bmi_value < 18.5:
        return "偏瘦"
    elif bmi_value < 24:
        return "正常"
    elif bmi_value < 28:
        return "超重"          # ← 这里用「超重」，是需求里定的术语，不要自己改成「偏胖」
    else:
        return "肥胖"


# ─────────────────────────────────────────────────────────
# 第 2 块：assert 自检（Day 2 欠的那两条，现在还上了）
#
# assert 读作「我断言这里成立」。条件为 True 时什么都不发生；
# 为 False 时程序立刻抛 AssertionError 停下。
#
# 这是最廉价的自动化测试：改代码之前跑一遍、改完再跑一遍，
# 只要断言还全过，就说明你没把原来的功能改坏。
# 第 10 周会学正规的评测体系，但原理和这行 assert 完全一样。
#
# 为什么浮点数要比「差值小于 0.01」而不是直接 == ？
# 因为 70 / 1.75**2 = 22.857142857...，浮点数存不进无限小数，
# 直接写 == 22.86 会因为微小误差判成 False。这是所有语言的共性。
# ─────────────────────────────────────────────────────────

def run_self_checks():
    """跑一遍自检。放在函数里，是为了让它既能被 __main__ 调用，
    又不会在别人 import 时自动执行。"""
    assert abs(calc_bmi(1.75, 70) - 22.86) < 0.01, "1.75m 70kg 应该约等于 22.86"
    assert abs(calc_bmi(1.60, 45) - 17.58) < 0.01, "1.60m 45kg 应该约等于 17.58"
    assert bmi_category(22.86) == "正常", "22.86 应该判为正常"
    assert bmi_category(17.58) == "偏瘦", "17.58 应该判为偏瘦"
    assert bmi_category(27.34) == "超重", "27.34 应该判为超重"
    assert bmi_category(30.0) == "肥胖", "30.0 应该判为肥胖"
    assert calc_bmi(0, 70) is None, "身高为 0 应该返回 None"      # ← 判断 None 用 is，Day 3 讲的
    assert calc_bmi(1.70, -5) is None, "体重为负应该返回 None"
    return 8            # 走到这里说明 8 条全过了


# ─────────────────────────────────────────────────────────
# 第 3 块：if __name__ == "__main__":  —— Day 1 那个问题现在有答案了
#
# Day 1 你答「只有直接运行时才执行，被 import 时不执行」，完全正确。
# 今天你第一次真正需要它，原因在这里：
#
# 如果那 8 行 assert 是【裸的】放在文件里（我第一版就是这么写的，写错了），
# 别人 import 这个文件想借用 calc_bmi，Python 会把整个文件从头执行一遍，
# 于是他的终端上会莫名冒出你的自检输出；万一某条 assert 挂了，
# 【他的程序直接崩在你的文件里】——他还不知道发生了什么。
#
# 所以规矩是：
#   ✅ 函数定义放外面 → import 时能拿到，没有副作用
#   ✅ 会「做事」的代码（打印、跑测试、读文件）放 __main__ 里面 → 只有直接运行才动
# ─────────────────────────────────────────────────────────

if __name__ == "__main__":
    # 下面这段只有运行 python bmi_calculator.py 时才执行
    passed = run_self_checks()
    print(f"✓ {passed} 条自检全部通过")

    print("\n几个样例（身高 / 体重 → BMI / 分类）：")
    print("-" * 46)

    # 列表套字典 —— 今天第 6 节的核心形状，真实数据都长这样
    samples = [
        {"姓名": "张三", "身高": 1.75, "体重": 70},
        {"姓名": "李四", "身高": 1.60, "体重": 45},
        {"姓名": "王五", "身高": 1.80, "体重": 95},
        {"姓名": "赵六", "身高": 1.70, "体重": 79},
        {"姓名": "错误示范", "身高": 0, "体重": 60},     # 非法输入
    ]

    for person in samples:
        value = calc_bmi(person["身高"], person["体重"])

        if value is None:
            # 非法输入走这条，不会崩，只是提示
            print(f'  {person["姓名"]:<8} 输入不合法（身高 {person["身高"]}）')
            continue                                    # Day 4 学的：跳过本轮，进下一条

        category = bmi_category(value)
        # f-string 嵌套时，内层用另一类引号（这里是单引号），否则和外面的双引号撞车
        print(f'  {person["姓名"]:<8} {person["身高"]}m / {person["体重"]}kg'
              f' → BMI {value:.1f}  {category}')

    print()
